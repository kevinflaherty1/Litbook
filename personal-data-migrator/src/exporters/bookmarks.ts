import type { Bundle, Platform, SavedItem } from "../model/types.ts";

/*
 * Likes and saves can't be "re-posted" anywhere, but they migrate well as
 * bookmarks. Formats:
 *   html  Netscape bookmark file: imports into Chrome, Firefox, Safari, Edge,
 *         Raindrop, Pocket, Pinboard… Collections become folders.
 *   csv   one row per item, for spreadsheets.
 *   json  the SavedItems themselves.
 *
 * Saved items are other people's content, so treat every field as hostile:
 * HTML-escape all text, only emit http(s) links (no `javascript:` or `data:`
 * URLs in a file that a browser will import), and neutralise spreadsheet
 * formula injection in CSV cells.
 */

export type BookmarkFormat = "html" | "csv" | "json";

export interface BookmarkOptions {
  /** Downvotes aren't something you'd bookmark; opt in explicitly. */
  includeDownvotes?: boolean;
}

export interface BookmarkExport {
  content: string;
  exported: number;
  /** Items left out because their URL was missing or not http(s). */
  droppedUnsafe: number;
}

const PLATFORM_NAME: Record<Platform, string> = { instagram: "Instagram", twitter: "X", reddit: "Reddit" };

export function safeHttpUrl(value: string | undefined): string | undefined {
  if (!value) return undefined;
  try {
    const url = new URL(value);
    return url.protocol === "https:" || url.protocol === "http:" ? url.href : undefined;
  } catch {
    return undefined;
  }
}

export function escapeHtml(text: string): string {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

/** CSV cell, quoted, with a leading quote added to anything a spreadsheet would run as a formula. */
export function csvCell(value: string | undefined): string {
  let v = (value ?? "").replace(/\r?\n/g, " ");
  if (/^[=+\-@\t\r]/.test(v)) v = `'${v}`;
  return `"${v.replace(/"/g, '""')}"`;
}

function title(item: SavedItem): string {
  if (item.textPreview) {
    const oneLine = item.textPreview.replace(/\s+/g, " ").trim();
    return oneLine.length > 120 ? `${oneLine.slice(0, 119)}…` : oneLine;
  }
  const by = item.author ? `@${item.author}` : item.community ? `r/${item.community}` : "";
  return [
    by,
    `${PLATFORM_NAME[item.source.platform]} ${item.targetType === "unknown" ? "item" : item.targetType}`,
  ]
    .filter(Boolean)
    .join(" · ");
}

function folderFor(item: SavedItem): string {
  if (item.kind === "like") return "Liked";
  if (item.kind === "save") return "Saved";
  return item.direction === "down" ? "Downvoted" : "Upvoted";
}

function selectItems(bundle: Bundle, opts: BookmarkOptions): { items: SavedItem[]; dropped: number } {
  let dropped = 0;
  const items = (bundle.saved ?? []).filter((item) => {
    if (item.kind === "vote" && item.direction === "down" && !opts.includeDownvotes) return false;
    if (!safeHttpUrl(item.source.url)) {
      dropped++;
      return false;
    }
    return true;
  });
  return { items, dropped };
}

function toHtml(bundle: Bundle, items: SavedItem[]): string {
  const root = `${PLATFORM_NAME[bundle.source]} @${bundle.profile.handle}`;
  const link = (item: SavedItem, indent: string) => {
    const addDate = item.savedAt ? ` ADD_DATE="${Math.floor(Date.parse(item.savedAt) / 1000)}"` : "";
    const tags = [bundle.source, item.kind, item.community, ...item.collections].filter(Boolean).join(",");
    return `${indent}<DT><A HREF="${escapeHtml(safeHttpUrl(item.source.url)!)}"${addDate} TAGS="${escapeHtml(tags)}">${escapeHtml(title(item))}</A>`;
  };
  const folder = (name: string, body: string[], indent: string) => [
    `${indent}<DT><H3>${escapeHtml(name)}</H3>`,
    `${indent}<DL><p>`,
    ...body,
    `${indent}</DL><p>`,
  ];

  const groups = new Map<string, SavedItem[]>();
  for (const item of items) groups.set(folderFor(item), [...(groups.get(folderFor(item)) ?? []), item]);

  const body: string[] = [];
  for (const [name, group] of groups) {
    const inner: string[] = [];
    if (name === "Saved") {
      // One subfolder per collection; an item filed in two collections appears in both.
      for (const c of bundle.collections ?? []) {
        const members = group.filter((i) => i.collections.includes(c.name));
        if (members.length)
          inner.push(
            ...folder(
              c.name,
              members.map((i) => link(i, "        ")),
              "      ",
            ),
          );
      }
      inner.push(...group.filter((i) => i.collections.length === 0).map((i) => link(i, "      ")));
    } else {
      inner.push(...group.map((i) => link(i, "      ")));
    }
    body.push(...folder(name, inner, "    "));
  }

  return [
    "<!DOCTYPE NETSCAPE-Bookmark-file-1>",
    "<!-- Generated by personal-data-migrator. -->",
    '<META HTTP-EQUIV="Content-Type" CONTENT="text/html; charset=UTF-8">',
    "<TITLE>Bookmarks</TITLE>",
    "<H1>Bookmarks</H1>",
    "<DL><p>",
    ...folder(root, body, "  "),
    "</DL><p>",
    "",
  ].join("\n");
}

function toCsv(items: SavedItem[]): string {
  const header = ["kind", "url", "title", "author", "community", "collections", "saved_at", "platform", "id"];
  const rows = items.map((i) =>
    [
      i.kind === "vote" ? `${i.direction}vote` : i.kind,
      safeHttpUrl(i.source.url),
      title(i),
      i.author,
      i.community,
      i.collections.join("; "),
      i.savedAt,
      i.source.platform,
      i.source.id,
    ]
      .map(csvCell)
      .join(","),
  );
  return [header.join(","), ...rows].join("\r\n") + "\r\n";
}

export function exportBookmarks(
  bundle: Bundle,
  format: BookmarkFormat,
  opts: BookmarkOptions = {},
): BookmarkExport {
  const { items, dropped } = selectItems(bundle, opts);
  const content =
    format === "html"
      ? toHtml(bundle, items)
      : format === "csv"
        ? toCsv(items)
        : JSON.stringify({ bundleId: bundle.id, collections: bundle.collections ?? [], items }, null, 2);
  return { content, exported: items.length, droppedUnsafe: dropped };
}
